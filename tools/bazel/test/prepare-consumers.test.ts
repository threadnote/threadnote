import {mkdtempSync, rmSync, statSync, symlinkSync, utimesSync} from '@threadnote/testing/node-fs';
import {tmpdir} from '@threadnote/testing/node-os';
import {join} from '@threadnote/testing/node-path';
import fc from 'fast-check';
import {expect, it} from 'vitest';
import {collectSourceIdentity, generationDigest, readPreparedInventory} from '../prepare.mjs';

const metadata = '{"schemaVersion":1}';
const fixture = async () => {
  const root = mkdtempSync(join(tmpdir(), 'bazel-consumer-'));
  await Bun.write(join(root, '.gitignore'), '.context/\napps/website/.bazel-inputs/\n');
  await Bun.write(join(root, 'package.json'), '{"private":true,"dependencies":{},"devDependencies":{}}');
  await Bun.write(join(root, 'apps/website/package.json'), '{"name":"@fixture/website","private":true}');
  await Bun.write(
    join(root, 'apps/website/tools/site-prepared-metadata.ts'),
    `await Bun.write('apps/website/.bazel-inputs/metadata.json', ${JSON.stringify(metadata)});`,
  );
  await Bun.write(join(root, 'apps/website/.bazel-inputs/metadata.json'), metadata);
  await Bun.write(join(root, 'source.ts'), 'export const x = 1;');
  const inventory = JSON.stringify({version: 1, testSuites: [], targets: [{label: '//:fixture', kind: 'test'}]});
  const build = '# Generated by tools/bazel/generate.mjs.\n';
  await Bun.write(join(root, 'BUILD.bazel'), build);
  await Bun.write(join(root, 'tools/bazel/targets.json'), inventory);
  for (const args of [
    ['init', '-q'],
    ['add', '.'],
    [
      '-c',
      'user.name=Fixture',
      '-c',
      'user.email=fixture@example.com',
      '-c',
      'commit.gpgsign=false',
      'commit',
      '-qm',
      'fixture',
    ],
  ]) {
    const child = Bun.spawnSync(['git', ...args], {cwd: root, stdout: 'pipe', stderr: 'pipe'});
    if (child.exitCode !== 0) throw new Error(new TextDecoder().decode(child.stderr));
  }
  const identity = await collectSourceIdentity(root);
  const generation = {...identity, inventoryDigest: generationDigest(inventory)};
  const receipt = {
    ...generation,
    version: 2,
    inventoryCount: 1,
    outputs: [
      {path: 'BUILD.bazel', sha256: generationDigest(build)},
      {path: 'tools/bazel/targets.json', sha256: generationDigest(inventory)},
    ],
  };
  await Bun.write(join(root, '.context/bazel-generated/receipt.json'), JSON.stringify(receipt));
  return {root, generation};
};

it('reuses only content-verified output and binds reads to the expected generation', async () => {
  const {root, generation} = await fixture();
  try {
    const before = statSync(join(root, 'BUILD.bazel')).mtimeMs;
    const first = await readPreparedInventory({root, expectedGeneration: generation});
    expect((await readPreparedInventory({root, allowStaged: true})).generation).toEqual(generation);
    const reordered = {
      inventoryDigest: generation.inventoryDigest,
      sourceDigest: generation.sourceDigest,
      headSha: generation.headSha,
    };
    expect((await readPreparedInventory({root, expectedGeneration: reordered})).inventory).toEqual(first.inventory);
    expect(statSync(join(root, 'BUILD.bazel')).mtimeMs).toBe(before);
    await expect(
      readPreparedInventory({root, expectedGeneration: {...generation, headSha: 'different'}}),
    ).rejects.toThrow('generation mismatch');
  } finally {
    rmSync(root, {recursive: true, force: true});
  }
});

it('invalidates changed source even when timestamps and size are preserved', async () => {
  const {root, generation} = await fixture();
  try {
    const path = join(root, 'source.ts');
    const before = statSync(path);
    await Bun.write(path, 'export const x = 2;');
    utimesSync(path, before.atime, before.mtime);
    expect(statSync(path).size).toBe(before.size);
    expect((await collectSourceIdentity(root)).sourceDigest).not.toBe(generation.sourceDigest);
    // This intentionally incomplete source fixture cannot regenerate the real
    // application graph. A stale successful read would hide invalidation.
    await expect(readPreparedInventory({root, allowStaged: true})).rejects.toThrow();
  } finally {
    rmSync(root, {recursive: true, force: true});
  }
});

it('tracks legitimate untracked filenames including leading whitespace, additions and deletions', async () => {
  const {root, generation} = await fixture();
  try {
    const path = join(root, ' leading.ts');
    await Bun.write(path, 'export const a = 1;');
    const first = await collectSourceIdentity(root);
    expect(first.sourceDigest).not.toBe(generation.sourceDigest);
    await Bun.write(path, 'export const a = 2;');
    expect((await collectSourceIdentity(root)).sourceDigest).not.toBe(first.sourceDigest);
    await Bun.file(path).delete();
    expect((await collectSourceIdentity(root)).sourceDigest).toBe(generation.sourceDigest);
  } finally {
    rmSync(root, {recursive: true, force: true});
  }
});

it.each(['BUILD.bazel', 'tools/bazel/targets.json'])(
  'rejects corrupted generated output %s rather than trusting its receipt',
  async path => {
    const {root} = await fixture();
    try {
      await Bun.write(
        join(root, path),
        path === 'BUILD.bazel' ? '# Generated by tools/bazel/generate.mjs.\ncorrupt' : 'corrupt',
      );
      await expect(readPreparedInventory({root})).rejects.toThrow();
    } finally {
      rmSync(root, {recursive: true, force: true});
    }
  },
);

it('allows only an explicitly staged inventory without a source checkout', async () => {
  const root = mkdtempSync(join(tmpdir(), 'bazel-stage-'));
  try {
    const inventory = {version: 1, targets: [], testSuites: []};
    await Bun.write(join(root, 'tools/bazel/targets.json'), JSON.stringify(inventory));
    expect(await readPreparedInventory({root, allowStaged: true})).toEqual({inventory, generation: null});
    await expect(readPreparedInventory({root, allowStaged: true, expectedGeneration: {}})).rejects.toThrow('staged');
    expect(await Bun.file(join(root, '.context/bazel-generated/receipt.json')).exists()).toBe(false);
  } finally {
    rmSync(root, {recursive: true, force: true});
  }
});

it('has content round trips independent of file timestamps', async () => {
  const {root} = await fixture();
  try {
    const path = join(root, 'sample.bin');
    await fc.assert(
      fc.asyncProperty(fc.integer({min: 0, max: 255}), fc.integer({min: 1, max: 255}), async (value, delta) => {
        await Bun.write(path, new Uint8Array([value]));
        const first = (await collectSourceIdentity(root)).sourceDigest;
        await Bun.write(path, new Uint8Array([(value + delta) % 256]));
        expect((await collectSourceIdentity(root)).sourceDigest).not.toBe(first);
        await Bun.write(path, new Uint8Array([value]));
        expect((await collectSourceIdentity(root)).sourceDigest).toBe(first);
      }),
      {numRuns: 12},
    );
  } finally {
    rmSync(root, {recursive: true, force: true});
  }
});

it.skipIf(process.platform === 'win32')(
  'hashes directory symlink identity without reading a directory as file data',
  async () => {
    const {root, generation} = await fixture();
    try {
      const link = join(root, 'linked');
      symlinkSync('apps/website', link);
      const directory = await collectSourceIdentity(root);
      expect(directory.sourceDigest).not.toBe(generation.sourceDigest);
      await Bun.file(link).delete();
      symlinkSync('source.ts', link);
      expect((await collectSourceIdentity(root)).sourceDigest).not.toBe(directory.sourceDigest);
    } finally {
      rmSync(root, {recursive: true, force: true});
    }
  },
);

import {Array as EffectArray, Option as EffectOption} from 'effect';
// Bun's fs compatibility API supplies atomic rename, link metadata and synchronous
// stat checks. Content I/O, hashing, spawning and publication locking use Bun APIs.
// oxlint-disable-next-line effecttsgo/node-builtin-import
import {lstatSync, readlinkSync, renameSync, statSync} from 'node:fs';
// oxlint-disable-next-line effecttsgo/node-builtin-import -- Build bootstrap uses Bun's path utilities without an Effect service layer.
import {join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {Database} from 'bun:sqlite';
import {listRepositoryFiles} from './repository-inputs.mjs';
import {buildGenerationModel} from './generation-model.mjs';
import * as EffectRecord from 'effect/Record';
import * as EffectString from 'effect/String';
import * as Effect from 'effect';

const stateDirectory = '.context/bazel-generated';
export const generationReceiptPath = `${stateDirectory}/receipt.json`;
export const generationDigest = content => new Bun.CryptoHasher('sha256').update(content).digest('hex');

const rootPath = () => fileURLToPath(new URL('../..', import.meta.url));
const outputPath = path =>
  /^(?:BUILD\.bazel|(?:apps|packages)\/[^/]+\/BUILD\.bazel|tools\/bazel\/targets\.json)$/u.test(path);
const git = (root, args) => {
  const child = Bun.spawnSync(['git', ...args], {cwd: root, stdout: 'pipe', stderr: 'pipe'});
  return {code: child.exitCode, text: new TextDecoder().decode(child.stdout)};
};
const sourceCheckout = root => {
  const inside = git(root, ['rev-parse', '--is-inside-work-tree']);
  return (
    inside.code === 0 &&
    Effect.pipe(inside.text, EffectString.trim) === 'true' &&
    Effect.pipe(git(root, ['rev-parse', '--show-prefix']).text, EffectString.trim) === ''
  );
};

/** Content identity includes legitimate untracked input and explicit prepared data. */
export const collectSourceIdentity = async root => {
  const repositoryFiles = listRepositoryFiles(root);
  const head = git(root, ['rev-parse', '--verify', 'HEAD']);
  if (head.code !== 0) throw new Error('Bazel preparation requires a source checkout with a Git HEAD');
  const paths = [...new Set([...repositoryFiles, 'apps/website/.bazel-inputs/metadata.json'])].sort();
  const entries = [];
  for (let offset = 0; offset < paths.length; offset += 64) {
    const batch = await Promise.all(
      EffectArray.map(paths.slice(offset, offset + 64), async path => {
        if (
          path === '.context' ||
          Effect.pipe(path, EffectString.startsWith('.context/')) ||
          path === 'tools/bazel/targets.json'
        )
          return null;
        const file = Bun.file(join(root, path));
        if (
          outputPath(path) &&
          (!(await file.exists()) ||
            Effect.pipe(await file.text(), EffectString.startsWith('# Generated by tools/bazel/generate.mjs.')))
        )
          return null;
        try {
          const stat = lstatSync(join(root, path));
          const link = stat.isSymbolicLink() ? readlinkSync(join(root, path)) : null;
          const directory = stat.isDirectory() || (stat.isSymbolicLink() && statSync(join(root, path)).isDirectory());
          const content = directory ? null : generationDigest(await file.bytes());
          return [path, stat.mode & 0o777, link, content];
        } catch (error) {
          if (error.code !== 'ENOENT') throw error;
          return [path, 'missing'];
        }
      }),
    );
    entries.push(...EffectArray.filter(batch, entry => entry !== null));
  }
  return {
    headSha: Effect.pipe(head.text, EffectString.trim),
    sourceDigest: generationDigest(JSON.stringify([Bun.version, Effect.pipe(head.text, EffectString.trim), entries])),
  };
};

const optionalJson = async path => {
  try {
    return await Bun.file(path).json();
  } catch (error) {
    if (error.code === 'ENOENT' || error instanceof SyntaxError) return undefined;
    throw error;
  }
};
const validReceipt = async (root, receipt, identity) => {
  if (
    receipt?.version !== 2 ||
    receipt.sourceDigest !== identity.sourceDigest ||
    receipt.headSha !== identity.headSha ||
    !EffectArray.isArray(receipt.outputs)
  )
    return false;
  const paths = new Set();
  for (const entry of receipt.outputs) {
    if (
      !entry ||
      typeof entry.path !== 'string' ||
      !outputPath(entry.path) ||
      paths.has(entry.path) ||
      !/^[a-f0-9]{64}$/u.test(entry.sha256)
    )
      return false;
    paths.add(entry.path);
    const file = Bun.file(join(root, entry.path));
    if (!(await file.exists()) || generationDigest(await file.bytes()) !== entry.sha256) return false;
  }
  return (
    paths.has('BUILD.bazel') &&
    paths.has('tools/bazel/targets.json') &&
    receipt.inventoryDigest === receipt.outputs.find(entry => entry.path === 'tools/bazel/targets.json')?.sha256
  );
};
const resultFor = (receiptPath, receipt) => ({
  receiptPath,
  outputCount: receipt.outputs.length,
  inventoryCount: receipt.inventoryCount,
  generation: {headSha: receipt.headSha, sourceDigest: receipt.sourceDigest, inventoryDigest: receipt.inventoryDigest},
});

// SQLite's process-safe writer lock is released by the OS on crash. There is no
// stale PID file to delete, or lease whose recovery could race another preparer.
const acquireLock = async root => {
  await Bun.write(join(root, stateDirectory, '.directory'), '');
  const db = new Database(join(root, stateDirectory, 'prepare.sqlite'));
  const deadline = Date.now() + 120_000;
  try {
    while (true) {
      try {
        db.exec('BEGIN IMMEDIATE');
        return () => {
          try {
            db.exec('ROLLBACK');
          } finally {
            db.close();
          }
        };
      } catch (error) {
        if (error.code !== 'SQLITE_BUSY') throw error;
        if (Date.now() >= deadline) throw new Error('Timed out waiting for the Bazel preparation lock', {cause: error});
        await Bun.sleep(25);
      }
    }
  } catch (error) {
    db.close();
    throw error;
  }
};

let temporarySequence = 0;
const atomicWrite = async (root, absolute, content) => {
  // A killed process may leave this file behind. Staging must stay outside
  // authored source discovery, even for broad repository-contract targets.
  const temporary = join(root, stateDirectory, 'staging', `${process.pid}-${temporarySequence++}.tmp`);
  try {
    await Bun.write(temporary, content);
    renameSync(temporary, absolute);
  } finally {
    if (await Bun.file(temporary).exists()) await Bun.file(temporary).delete();
  }
};

/** Materialize one complete flat graph before any consumer reads its inventory. */
export const prepareBazelWorkspace = async ({
  root: inputRoot = rootPath(),
  modelOptions = {},
  produceMetadata = true,
} = {}) => {
  const root = resolve(inputRoot);
  const release = await acquireLock(root);
  try {
    try {
      for (const name of new Bun.Glob('*.tmp').scanSync({cwd: join(root, stateDirectory, 'staging')})) {
        if (/^\d+-\d+\.tmp$/u.test(name)) await Bun.file(join(root, stateDirectory, 'staging', name)).delete();
      }
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (produceMetadata) {
      const child = Bun.spawnSync(
        [
          process.execPath,
          'apps/website/tools/site-prepared-metadata.ts',
          '--output',
          'apps/website/.bazel-inputs/metadata.json',
        ],
        {cwd: root, stdout: 'inherit', stderr: 'inherit'},
      );
      if (child.exitCode !== 0) throw new Error(`Website metadata preparation failed (${child.exitCode})`);
    }
    const receiptPath = join(root, generationReceiptPath);
    const reusable = produceMetadata && EffectRecord.keys(modelOptions).length === 0;
    const identity = reusable ? await collectSourceIdentity(root) : undefined;
    const complete = await optionalJson(receiptPath);
    if (reusable && (await validReceipt(root, complete, identity))) return resultFor(receiptPath, complete);
    const model = await buildGenerationModel({...modelOptions, root});
    if (reusable && (await collectSourceIdentity(root)).sourceDigest !== identity.sourceDigest)
      throw new Error('Source changed during Bazel preparation; retry');
    const ownershipPath = join(root, stateDirectory, 'ownership.json');
    let previous;
    for (const path of [ownershipPath, receiptPath]) {
      try {
        previous = await Bun.file(path).json();
        break;
      } catch (error) {
        if (error.code !== 'ENOENT' && !(error instanceof SyntaxError)) throw error;
      }
    }
    const receipt = {
      version: 2,
      ...identity,
      inventoryCount: model.inventory.length,
      outputs: EffectArray.map([...model.output], ([path, content]) => ({path, sha256: generationDigest(content)})),
    };
    receipt.outputs.sort((left, right) => left.path.localeCompare(right.path));
    receipt.inventoryDigest = EffectOption.getOrUndefined(
      EffectArray.findFirst(receipt.outputs, entry => entry.path === 'tools/bazel/targets.json'),
    )?.sha256;
    // Retain ownership across a failed publication, including newly created
    // outputs. The completion receipt alone is intentionally invalidated below.
    const owned = new Map((previous?.outputs ?? []).map(entry => [entry.path, entry]));
    for (const entry of receipt.outputs) owned.set(entry.path, entry);
    await atomicWrite(root, ownershipPath, JSON.stringify({version: 1, outputs: [...owned.values()]}));
    if (await Bun.file(receiptPath).exists()) await Bun.file(receiptPath).delete();
    for (const [path, content] of model.output) {
      const absolute = join(root, path);
      const file = Bun.file(absolute);
      if ((await file.exists()) && (await file.text()) === content) continue;
      await atomicWrite(root, absolute, content);
    }
    for (const prior of previous?.outputs ?? []) {
      if (
        model.output.has(prior.path) ||
        !/^(?:[^/]+\/)*BUILD\.bazel$/u.test(prior.path) ||
        prior.path.split('/').includes('..')
      )
        continue;
      const file = Bun.file(join(root, prior.path));
      if ((await file.exists()) && Effect.pipe(await file.text(), EffectString.startsWith(model.generatedHeader)))
        await file.delete();
    }
    await atomicWrite(root, receiptPath, JSON.stringify(receipt, null, 2) + '\n');
    await atomicWrite(root, ownershipPath, JSON.stringify(receipt));
    return resultFor(receiptPath, receipt);
  } finally {
    release();
  }
};

/** @param {{root?: string, allowStaged?: boolean, expectedGeneration?: object}} [options] */
export const readPreparedInventory = async ({
  root: inputRoot = rootPath(),
  allowStaged = false,
  expectedGeneration,
} = {}) => {
  const root = resolve(inputRoot);
  let generation = null;
  if (allowStaged && !sourceCheckout(root)) {
    if (expectedGeneration) throw new Error('A staged inventory cannot validate a source generation');
  } else {
    generation = (await prepareBazelWorkspace({root})).generation;
  }
  const text = await Bun.file(join(root, 'tools/bazel/targets.json')).text();
  if (generation && generationDigest(text) !== generation.inventoryDigest)
    throw new Error('Bazel inventory changed after preparation; retry');
  if (
    expectedGeneration &&
    EffectArray.some(
      ['headSha', 'sourceDigest', 'inventoryDigest'],
      key => generation?.[key] !== expectedGeneration[key],
    )
  )
    throw new Error('Bazel generation mismatch: worker differs from planner');
  const inventory = JSON.parse(text);
  if (inventory?.version !== 1 || !EffectArray.isArray(inventory.targets) || !EffectArray.isArray(inventory.testSuites))
    throw new Error('Invalid Bazel target inventory');
  return {inventory, generation};
};

if (import.meta.main) await prepareBazelWorkspace();

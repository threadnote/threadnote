import {it as effectIt} from '@effect/vitest';
import * as BunServices from '@effect/platform-bun/BunServices';
import {Array as EffectArray, Effect, FileSystem, Path, String as EffectString} from 'effect';
import {expect} from 'vitest';
import {generateCodeGraphLanguageCatalog} from '../../../../scripts/generate-code-graph-language-catalog.js';

effectIt.layer(BunServices.layer)(it => {
  it.effect('preserves an equivalent CRLF catalog and writes actual pack changes once', () =>
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      const root = yield* fs.makeTempDirectoryScoped({prefix: 'language-catalog-'});
      const languages = path.join(root, 'packages', 'graph', 'src', 'languages');
      for (const directory of ['zeta', 'alpha']) {
        yield* fs.makeDirectory(path.join(languages, directory), {recursive: true});
        yield* fs.writeFileString(path.join(languages, directory, 'pack.ts'), '');
      }
      const target = path.join(languages, 'catalog.generated.ts');
      const crlf = EffectArray.join(
        [
          '// Generated by scripts/generate-code-graph-language-catalog.ts. Do not edit by hand.',
          "import {codeGraphLanguagePack as alpha} from './alpha/pack.js';",
          "import {codeGraphLanguagePack as zeta} from './zeta/pack.js';",
          '',
          'export const BUILTIN_CODE_GRAPH_LANGUAGE_PACKS = [',
          '  alpha,',
          '  zeta,',
          '] as const;',
          '',
        ],
        '\r\n',
      );
      yield* fs.writeFileString(target, crlf);
      const writes: string[] = [];
      const observedFs = FileSystem.FileSystem.of({
        ...fs,
        writeFileString: (file, content, options) =>
          Effect.gen(function* () {
            writes.push(file);
            yield* fs.writeFileString(file, content, options);
          }),
      });
      const generate = generateCodeGraphLanguageCatalog(root).pipe(
        Effect.provideService(FileSystem.FileSystem, observedFs),
      );

      yield* generate;
      expect(yield* fs.readFileString(target)).toBe(crlf);
      expect(writes).toEqual([]);

      yield* fs.makeDirectory(path.join(languages, 'new-language'));
      yield* fs.writeFileString(path.join(languages, 'new-language', 'pack.ts'), '');
      yield* generate;
      const updated = yield* fs.readFileString(target);
      expect(updated).toContain("import {codeGraphLanguagePack as newLanguage} from './new-language/pack.js';");
      expect(updated).toContain('  alpha,\n  newLanguage,\n  zeta,');
      expect(updated).not.toBe(crlf);
      expect(EffectString.includes('\r')(updated)).toBe(false);
      expect(writes).toEqual([target]);

      yield* generate;
      expect(yield* fs.readFileString(target)).toBe(updated);
      expect(writes).toEqual([target]);
    }),
  );
});

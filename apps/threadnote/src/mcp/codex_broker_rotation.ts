export const CODEX_MCP_RELEASE_ENV = 'THREADNOTE_MCP_RELEASE';
export const CODEX_MCP_LAUNCHER_DEFERRED = 'the managed MCP launcher does not match the active release';

export const hasActiveMcpLauncher = Effect.fn('mcp.codexMcpLauncher')(function* (releaseRoot: string) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const system = yield* SystemInfo;
  const launcher = yield* commandLauncherPath('mcp');
  // Installers can render an established logical root (for example /var on
  // macOS). Accept only exact generated bytes associated with this release.
  const candidates = EffectArray.dedupe([
    releaseRoot,
    path.join(installationRoot(path, system), 'versions', path.basename(releaseRoot)),
    path.dirname(system.executablePath),
  ]);
  const generated = yield* Effect.forEach(candidates, root =>
    renderCommandShim(root, 'mcp').pipe(Effect.map(content => ({root, content}))),
  );
  const encoder = new TextEncoder();
  const maximumBytes = Math.max(...EffectArray.map(generated, item => encoder.encode(item.content).length));
  const actual = yield* fromPromise('verify managed MCP launcher', async () => {
    const info = await runtimeLstat(launcher);
    if (
      !info.isFile() ||
      info.size > BigInt(maximumBytes) ||
      (system.platform !== 'win32' && (info.mode & 0o100n) === 0n)
    ) {
      return undefined;
    }
    const contents = await runtimeReadBoundedStableRegularFile(launcher, maximumBytes, info);
    return new TextDecoder('utf-8', {fatal: true, ignoreBOM: true}).decode(contents);
  }).pipe(Effect.orElseSucceed(() => undefined));
  for (const {root, content} of generated) {
    if (actual !== content) continue;
    return (
      root === releaseRoot || (yield* fs.realPath(root).pipe(Effect.orElseSucceed(() => undefined))) === releaseRoot
    );
  }
  return false;
});

const hasCommittedMcpLauncher = Effect.fn('mcp.codexCommittedMcpLauncher')(function* (release: string | undefined) {
  const active = yield* activeInstalledRelease();
  return active !== undefined && active.version === release && (yield* hasActiveMcpLauncher(active.releaseRoot));
});

const MAX_CONFIG_BYTES = 4 * 1024 * 1024;

export const resolveCodexSetupHome = Effect.fn('mcp.codexSetupHome')(function* () {
  const system = yield* SystemInfo;
  return yield* expandPath(system.environment().CODEX_HOME || '~/.codex');
});

